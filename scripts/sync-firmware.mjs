// Copies the URTC build output (firmware/*.bin/.hex/.elf plus the
// <bin>.sha256 and <bin>.manifest.json sidecars) into public/firmware and
// regenerates src/lib/bundledFirmware.ts, so the files this app offers
// "locally" are always exactly the ones the URTC repo published - same
// names, same bytes, same signatures.
//
//   node scripts/sync-firmware.mjs [path/to/URTC/firmware]   (default ../URTC/firmware)
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(process.argv[2] ?? join(root, '..', 'URTC', 'firmware'));
const dst = join(root, 'public', 'firmware');

const index = JSON.parse(readFileSync(join(src, 'firmware_manifest.json'), 'utf8'));
const pick = (name) => {
  const file = index.components?.[name]?.files?.bin?.filename;
  if (!file) throw new Error(`firmware_manifest.json has no components.${name}.files.bin.filename`);
  return file;
};
const files = {
  mainApplication: pick('main_application'),
  slaveApplication: pick('slave_application'),
  mainBootloader: pick('main_bootloader'),
  slaveBootloader: pick('slave_bootloader'),
};

rmSync(dst, { recursive: true, force: true });
mkdirSync(dst, { recursive: true });
for (const bin of Object.values(files)) {
  const manifest = JSON.parse(readFileSync(join(src, `${bin}.manifest.json`), 'utf8'));
  const actual = createHash('sha256').update(readFileSync(join(src, bin))).digest('hex');
  if (actual !== manifest.sha256) throw new Error(`${bin}: sha256 ${actual} does not match its manifest ${manifest.sha256}`);
  const stem = bin.replace(/\.bin$/, '');
  for (const f of [bin, `${bin}.sha256`, `${bin}.manifest.json`, `${stem}.hex`, `${stem}.elf`]) {
    copyFileSync(join(src, f), join(dst, f));
  }
}
copyFileSync(join(src, 'firmware_manifest.json'), join(dst, 'firmware_manifest.json'));

writeFileSync(join(root, 'src', 'lib', 'bundledFirmware.ts'), `// GENERATED by scripts/sync-firmware.mjs from the URTC build output - do not edit by hand.
// The binaries in public/firmware/ are byte-identical to URTC's firmware/ folder
// and each ships its <bin>.sha256 and <bin>.manifest.json (with hmac_sha256).
export const BUNDLED_FIRMWARE = ${JSON.stringify(files, null, 2)} as const;
`);
console.log(`synced ${Object.keys(files).length} images from ${src}:`, files);
